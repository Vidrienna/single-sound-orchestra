def save_audio_to_wav(filename, audio, srate=44100):
  """Saves an audio array as a wav file"""
  audio = audio / np.max(np.abs(audio))
  write(filename, srate, audio.astype(np.float32))

def crude_filtering(signal: np.ndarray, frequency_range: tuple[float, float]) -> np.ndarray:
  '''
  Crude filtering on a signal.

  This function takes the input signal, converts that signal from a time domain
  to a frequency domain using the DFT, then zeroes out frequencies within the
  threshold given. The signal is then converted back to time domain
  using the inverse DFT and returned.

  Args:
    signal (np.ndarray): the samples of the signal
    threshold (tuple): the lower and upper frequency percentages (represented by floats 0.0:1.0)

  Returns:
    np.ndarray: the filtered signal
  '''
  # Convert the time-domain audio signal to a frequency-domain array of complex coefficients using fft
  # We use rfft because the audio samples are real-valued, so rfft returns only non-negative frequencies and avoids redundant info
  # makes it easier to isolate the range of frequencies (only have to do it once for non-negative frequencies)
  complex_spectrum = fft.rfft(signal)
  # Calculate the magnitude (absolute value) of each complex FFT coefficient
  magnitude_spectrum = np.abs(complex_spectrum)

  # Using frequency bins, we can isolate the range of frequencies we would like to remove
  num_bins = len(magnitude_spectrum)
  start = (frequency_range[0] * num_bins)
  end = (frequency_range[1] * num_bins)
  # Set the frequencies within the frequency range to zero, to remove those frequencies from the signal
  magnitude_spectrum[int(start):int(end)] = 0.0

  # Calculate the phase spectrum and recalculate the new complex magnitude spectrum to
  # prepare for reconstructing the signal back to the time domain
  phase_spectrum = np.angle(complex_spectrum)
  reconstructed_complex_spectrum = magnitude_spectrum * (np.cos(phase_spectrum)+1j*np.sin(phase_spectrum))

  # Use the inverse FFT to reconstruct the signal back to the time domain
  reconstructed_signal = fft.irfft(reconstructed_complex_spectrum)

  return reconstructed_signal


def band_pass_crude_filtering(signal: np.ndarray, frequency_range: tuple[float, float]) -> np.ndarray:
  '''
  Band-pass filtering on a signal.
  Uses the frequency range to calculate a lower frequency range and an upper frequency
  range. Then the crude_filtering function is used on the signal twice with each
  range to filter out the lower and upper ranges so that the final signal only contains
  the frequencies WITHIN the frequency range given to properly do band pass filtering.

  Args:
    signal (np.ndarray): the samples of the signal
    threshold (tuple): the lower and upper frequency percentages (represented by floats

  Returns:
    np.ndarray: the filtered signal
  '''
  lower_frequency_range = (0.0, frequency_range[0])
  upper_frequency_range = (frequency_range[1], 1.0)

  # filter out the frequencies in the lower frequency range
  lower_filtered_signal = crude_filtering(signal, lower_frequency_range)
  # filter out the freqs in the upper range of the lower_filtered_signal so that
  # final signal contains both ranges filtered out
  band_pass_filtered_signal = crude_filtering(lower_filtered_signal, upper_frequency_range)

  return band_pass_filtered_signal

