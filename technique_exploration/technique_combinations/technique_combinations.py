# CRUDE FILTERING CODE FROM Magnitude_Spectrum_Manipulation.ipynb
def crude_filtering(signal: np.ndarray, frequency_range: tuple[float, float]) -> np.ndarray:
  complex_spectrum = fft.rfft(signal)
  magnitude_spectrum = np.abs(complex_spectrum)

  num_bins = len(magnitude_spectrum)
  start = (frequency_range[0] * num_bins)
  end = (frequency_range[1] * num_bins)

  magnitude_spectrum[int(start):int(end)] = 0.0
  phase_spectrum = np.angle(complex_spectrum)
  reconstructed_complex_spectrum = magnitude_spectrum * (np.cos(phase_spectrum)+1j*np.sin(phase_spectrum))

  reconstructed_signal = fft.irfft(reconstructed_complex_spectrum)

  return reconstructed_signal


def band_pass_crude_filtering(signal: np.ndarray, frequency_range: tuple[float, float]) -> np.ndarray:
  lower_frequency_range = (0.0, frequency_range[0])
  upper_frequency_range = (frequency_range[1], 1.0)

  # filter out the frequencies in the lower frequency range
  lower_filtered_signal = crude_filtering(signal, lower_frequency_range)
  # filter out the freqs in the upper range of the lower_filtered_signal so that
  # final signal contains both ranges filtered out
  band_pass_filtered_signal = crude_filtering(lower_filtered_signal, upper_frequency_range)

  return band_pass_filtered_signal

