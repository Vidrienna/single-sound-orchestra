# Use the same stretching factor for both methods
stretch_factor = 1.25

wsola = wsola_time_stretch(tomsdiner_audio, stretch_factor)
pv = phase_vocoder_time_stretch(tomsdiner_audio, srate, 1/stretch_factor)

signals = {
    "Original": tomsdiner_audio,
    "WSOLA": wsola,
    "Phase Vocoder": pv
}

plt.figure(figsize=(14, 5))

for label, audio in signals.items():

    # Estimate fundamental frequency
    f0, _, _ = librosa.pyin(
        audio,
        sr=srate,
        frame_length=2048,
        hop_length=512,
        fmin=librosa.note_to_hz("C2"),
        fmax=librosa.note_to_hz("C7")
    )

    # Convert pitch to MIDI notes
    midi_pitch = librosa.hz_to_midi(f0)

    times = librosa.times_like(f0, sr=srate, hop_length=512)

    # Align original pitch contour with stretched audio
    if label == "Original":
        times = times * stretch_factor

    plt.plot(times, midi_pitch, label=label, alpha=0.8)

plt.xlabel("Time (seconds)")
plt.ylabel("Pitch (MIDI note)")
plt.title("Pitch Preservation: WSOLA vs Phase Vocoder")
plt.legend()
plt.grid(alpha=0.3)


