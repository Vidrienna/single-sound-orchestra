def save_audio_to_wav(filename, audio, srate=44100):
  """Saves an audio array as a wav file"""
  audio = audio / np.max(np.abs(audio))
  write(filename, srate, audio.astype(np.float32))

# WSOLA Time Stretching:
def wsola_time_stretch(audio, stretch_factor):
  audio_stretched = pytsmod.wsola(audio, stretch_factor)
  return audio_stretched

# stretch factor < 1 = faster, >1 = slower
tomsdiner_slow = wsola_time_stretch(tomsdiner_audio, 1.25)
tomsdiner_fast = wsola_time_stretch(tomsdiner_audio, 0.75)

save_audio_to_wav('audios/tomsdiner_slow_wsola.wav', tomsdiner_slow, srate)
ipd.Audio(tomsdiner_slow, rate=srate)

save_audio_to_wav('audios/tomsdiner_fast_wsola.wav', tomsdiner_fast, srate)
ipd.Audio(tomsdiner_fast, rate=srate)

# Phase Vocoder Time Stretching:

def phase_vocoder_time_stretch(audio, sample_rate, stretch_rate):
  # Convert to frequency domain
  D = librosa.stft(audio, n_fft=1024, hop_length=512)

  # Stretch the audio using the librosa phase_vocoder
  D_stretched = librosa.phase_vocoder(D, rate=stretch_rate, hop_length=512)

  # Reconstruct the audio back to time domain
  audio_stretched = librosa.istft(D_stretched, hop_length=512)

  return audio_stretched

# speed up factor (stretch_rate) >1 is faster, <1 is slower

tomsdiner_slow = phase_vocoder_time_stretch(tomsdiner_audio, srate, 0.25)
tomsdiner_fast = phase_vocoder_time_stretch(tomsdiner_audio, srate, 1.75)

