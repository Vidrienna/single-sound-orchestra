# We can extract the pitch contour using the pyin fundamental frequency estimator from librosa

hopSize = 1024 # How many samples we move forward before analyzing the next frame
winSize = 4096 # How many audio samples are analyzed at once


# Monophonic pitch extraction using librosa.pyin: try with C3-C6 and C4-C6
f0, voiced_flag, voiced_probs = librosa.pyin(
  vocals,
  sr=srate,
  frame_length=winSize,
  hop_length=hopSize,
  fmin=librosa.note_to_hz('C2'),
  fmax=librosa.note_to_hz('C6'),
  center=False
)

# Apply a median filter to the estimated pitch track to remove sudden isolated errors in pitch estimation
f0 = signal.medfilt(f0, kernel_size=3)

