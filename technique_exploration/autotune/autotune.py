# Find the closest target pitch
def closest(m, scale):
    return scale[np.argmin(np.abs(scale-m))]

# Basic autotune function: maps each pitch to target pitch and does pitch shifting without time stretching
def autotune(audio_signal, scale):
    output = np.zeros(len(audio_signal))
    for (m,o) in enumerate(offsets):
        mf0 = librosa.hz_to_midi(f0[m])
        frame = audio_signal[o:o+winSize]
        window = signal.windows.hann(len(frame))
        if not(np.isnan(mf0)):
            steps = mf0 - closest(mf0,scale)
            frame = librosa.effects.pitch_shift(frame, sr = srate, n_steps = -steps)
        frame = window * frame
        output[o:o+winSize] += frame
    return output

# PSOLA is the pitch modification method most associated with the "autotune" sound.
def autotune_psola(audio_signal, scale):
    fmin = librosa.note_to_hz('C2')
    fmax = librosa.note_to_hz('C7')
    mf0 = librosa.hz_to_midi(f0)
    corrected_f0 = [librosa.midi_to_hz(closest(mf, scale)) for mf in mf0]
    med_filtered = sig.medfilt(corrected_f0, kernel_size=3)
    output = psola.vocode(audio_signal, sample_rate=int(srate), target_pitch=med_filtered, fmin=fmin, fmax=fmax)
    return output

def autotune_and_mix(vocals, instrumental, scale, autotune_func):
    # Autotune the vocals using the chosen function and scale
    autotuned_vocals = autotune_func(vocals, scale)

    # Ensure both audio signals have the same length
    length = min(len(autotuned_vocals), len(instrumental))

    # Combine autotuned vocals with original instrumental
    final_audio = (
        autotuned_vocals[:length] +
        instrumental[:length]
    )

    # Prevent clipping
    peak = np.max(np.abs(final_audio))
    if peak > 1:
        final_audio = final_audio / peak

    return final_audio

