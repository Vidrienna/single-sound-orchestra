# Define scales and corresponding vocal outputs
scales = {
    "low": (low_scale, low_scale_output_vocals, low_scale_output_psola_vocals),
    "middle": (middle_scale, middle_scale_output_vocals, middle_scale_output_psola_vocals),
    "high": (high_scale, high_scale_output_vocals, high_scale_output_psola_vocals)
}

# Plot settings
start_time = 0
end_time = 4.8

start = int(start_time * srate)
end = int(end_time * srate)

# Generate one plot for each scale
for scale_name, (scale, autotune_audio, psola_audio) in scales.items():

    signals = {
        "Original": vocals,
        "Basic Autotune": autotune_audio,
        "PSOLA": psola_audio
    }

    plt.figure(figsize=(14, 5))

    for label, audio in signals.items():
        # Estimate fundamental frequency
        estimated_f0, _, _ = librosa.pyin(
            audio[start:end],
            sr=srate,
            frame_length=winSize,
            hop_length=hopSize,
            fmin=librosa.note_to_hz("C2"),
            fmax=librosa.note_to_hz("C7"),
            center=False
        )

        # Convert frequency to MIDI notes
        midi_pitch = librosa.hz_to_midi(estimated_f0)
        times = start_time + np.arange(len(midi_pitch)) * hopSize / srate

        plt.plot(times, midi_pitch, label=label, alpha=0.8)

    # Plot target scale notes as horizontal dashed lines
    for i, note in enumerate(scale):
        plt.axhline(
            note,
            color="red",
            linestyle="--",
            alpha=0.5,
            label="Target Scale Notes" if i == 0 else None
        )

    plt.xlabel("Time (seconds)")
    plt.ylabel("Pitch (MIDI note)")
    plt.title(f"Original vs Basic Autotune vs PSOLA ({scale_name.capitalize()} Scale)")
    plt.legend()
    plt.grid()

    # Save plot as PNG
    plt.savefig(f"plots/{scale_name}_scale_comparison.png",
                dpi=300, bbox_inches="tight")

    plt.show()
    plt.close()