# lets use flat magnitude reconstruction to "fade out" the song! Normally we would
# use amplitude envelopes for this, but this could produce an interesting effect

num_segments = len(tomsdiner) // 10000
segments = np.array_split(tomsdiner, num_segments)

faded_segments = []

for i, segment in enumerate(segments):
    if i < num_segments / 2:
        amplitude = 1.0
    else:
        amplitude = 1.0 - ((i - num_segments / 2) / (num_segments / 2 - 1))

    faded = flat_magnitude_reconstruct(segment, amplitude)
    faded_segments.append(faded)

fade_out = np.concatenate(faded_segments)

# sounds insane, lots of speckles and cracks, but interesting I guess?
ipd.Audio(fade_out, rate=srate, normalize=False)

# save audio
save_audio_to_wav('audios/fade_out_flat_magnitude_reconstructed_toms_diner.wav', fade_out, srate)