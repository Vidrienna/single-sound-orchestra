def save_audio_to_wav(filename, audio, srate=44100):
  """Saves an audio array as a wav file"""
  audio = audio / np.max(np.abs(audio))
  write(filename, srate, audio.astype(np.float32))

# slightly different from MIR book: takes amplitude as input instead of setting
# all amplitudes to 1
def flat_magnitude_reconstruct(signal: np.ndarray, amplitude: float) -> np.ndarray:
  '''
  Flat magnitude reconstruction on a signal.

  This function takes the input signal, converts the signal from time domain to
  frequency domain using the FFT, then sets all amplitudes to the same magnitude
  before converting the signal back to the time domain using the IFFT. The phase
  spectrum remains the same.

  Args:
    signal (np.ndarray): the samples of the signal
    amplitude (float): the amplitude, a float between 0.0 and 1.0

  Returns:
    np.ndarray: the reconstructed signal

  Raises:
    ValueError: if the amplitude is not between 0.0 and 1.0
  '''
  if (amplitude < 0.0) or (amplitude > 1.0):
    raise ValueError('Amplitude must be between 0.0 and 1.0')

  # Convert the time-domain audio signal to a frequency-domain array of complex coefficients using fft
  # We use rfft because the audio samples are real-valued, so rfft returns only non-negative frequencies and avoids redundant info
  complex_spectrum = fft.rfft(signal)

  # Set all magnitudes to the same given amplitude
  magnitude_spectrum = np.full(len(complex_spectrum), amplitude)

  # Phase spectrum remains unchanged
  phase_spectrum = np.angle(complex_spectrum)

  # reconstruct the signal in frequency domain with the new magnitude spectrum
  reconstructed_complex_spectrum = magnitude_spectrum *(np.cos(phase_spectrum) + 1j*np.sin(phase_spectrum))
  reconstructed_signal = fft.irfft(reconstructed_complex_spectrum)

  return reconstructed_signal


flat_toms_diner = flat_magnitude_reconstruct(tomsdiner, 1.0)
