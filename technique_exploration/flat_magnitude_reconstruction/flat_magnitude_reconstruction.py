# Notice the amplitude still fluctuates a bit. This is because we were setting the
# magnitudes of the frequency components to the same value, not the amplitudes of
# the time domain samples. Therefore every frequency component now has a magnitude
# of 1.0, but each component still has its original phase

# When we reconstructed the signal using the ifft, all of the frequency components
# were added together, and constructive interference (aligned sinusoids) and
# destructive interference (opposing sinusoids), creating large and small peaks.

# The maximum amplitude of the reconstructed wave is significantly decreased
# because we have reduced the stronger frequency components and increased the
# weaker frequncy components all to the same amplitudes, now their combined peaks
# are generally smaller.
